"""Initialize the Phase 1 PostgreSQL table."""

import sys
from pathlib import Path

from sqlalchemy import create_engine, text
from sqlalchemy.exc import SQLAlchemyError

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import DATABASE_URL  # noqa: E402

CREATE_TABLE = """
CREATE TABLE IF NOT EXISTS loan_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id VARCHAR(64) NOT NULL UNIQUE,
    age INTEGER,
    income NUMERIC,
    loan_amount NUMERIC,
    credit_score INTEGER,
    months_employed INTEGER,
    num_credit_lines INTEGER,
    interest_rate NUMERIC,
    loan_term INTEGER,
    dti_ratio NUMERIC,
    education VARCHAR(100),
    employment_type VARCHAR(100),
    marital_status VARCHAR(100),
    has_mortgage VARCHAR(10),
    has_dependents VARCHAR(10),
    loan_purpose VARCHAR(100),
    has_cosigner VARCHAR(10),
    "default" INTEGER,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
)
"""


def main() -> int:
    """Create the database table without dropping existing data."""
    print("Connecting to PostgreSQL...")
    engine = create_engine(DATABASE_URL, pool_pre_ping=True)
    try:
        with engine.begin() as connection:
            connection.execute(text("SELECT 1"))
            print("Connection successful.")
            print("Creating loan_applications table...")
            connection.execute(text(CREATE_TABLE))
        print("Database initialization completed.")
        return 0
    except SQLAlchemyError as exc:
        print(f"Database initialization failed: {exc}", file=sys.stderr)
        return 1
    finally:
        engine.dispose()


if __name__ == "__main__":
    raise SystemExit(main())
